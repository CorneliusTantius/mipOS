#!/usr/bin/env python3
"""
Extract the commands from the LFS book into one script per book section.

Usage:  python3 tools/extract-book.py LFS-BOOK-<version>-NOCHUNKS.html lfs/book

Each section of the book (for example "5.2. Binutils - Pass 1") becomes a
file like lfs/book/ch5/052-binutils-pass1.sh holding exactly the commands the
book prints, in order. Test-suite commands are wrapped in a check so they only
run when RUN_TESTS=yes. lfs/book/index.tsv lists every section with its
package tarball.

The LFS book's computer instructions may be extracted under the MIT License
(see lfs/book/LICENSE). This tool only copies them; mipOS's own changes live
in lfs/overrides/ and the build scripts.
"""
import html
import os
import re
import sys

src, outdir = sys.argv[1], sys.argv[2]
book = open(src, encoding="utf-8").read()

# Section anchors look like:  <a id="ch-tools-binutils-pass1" name=\n "ch-tools-binutils-pass1"></a>5.2. Binutils-2.47 - Pass 1
anchor = re.compile(r'<a id="(ch-[A-Za-z0-9-]+)"\s+name=\s*"\1"></a>(.*?)</h[123]>', re.S)
sections = []
for m in anchor.finditer(book):
    title = re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", "", m.group(2)))).strip()
    sections.append((m.group(1), title, m.start()))

block = re.compile(r'<pre class="userinput"><kbd\s+class=\s*"command">(.*?)</kbd></pre>', re.S)

# Commands that run a test suite (only run with RUN_TESTS=yes).
TEST = re.compile(r"(\bmake\b[^\n|]*\b(check|test|tests)\b|ninja test|meson test|ctest|"
                  r"runtest|test_harness|su tester|TESTSUITEFLAGS|make -k check|"
                  r"grep -E? ?[^\n]*\.log|expect -c)")

version_re = re.compile(r"^([A-Za-z0-9+._-]*?)-(\d[\w.]*)")

# Sections whose package can't be read from the title.
PKG_OVERRIDE = {"ch-tools-libstdcpp": "gcc", "ch-tools-linux-headers": "linux",
                "ch-bootable-kernel": "linux"}

def tarball_for(title):
    # "5.2. Binutils-2.47 - Pass 1" -> ("binutils", "2.47")
    name = re.sub(r"^\d+(\.\d+)*\.\s*", "", title)
    m = version_re.match(name)
    return (m.group(1).lower(), m.group(2)) if m else ("", "")


def version_of(pkg):
    # Find the version of a package from another section's title (e.g. gcc for libstdc++).
    for sid2, t2, _ in sections:
        p2, v2 = tarball_for(t2)
        if p2 == pkg:
            return v2
    return ""

os.makedirs(outdir, exist_ok=True)
index = []
for i, (sid, title, start) in enumerate(sections):
    end = sections[i + 1][2] if i + 1 < len(sections) else len(book)
    cmds = [html.unescape(re.sub(r"<[^>]+>", "", b)) for b in block.findall(book[start:end])]
    if not cmds:
        continue
    num = re.match(r"^(\d+)\.(\d+)(?:\.(\d+))?", title)
    chap = int(num.group(1)) if num else 0
    sub = int(num.group(2)) if num else 0
    subsub = int(num.group(3)) if num and num.group(3) else 0
    slug = re.sub(r"^ch-(tools|system|config|bootable|preps|partitioning|materials|finish)-", "", sid)
    rel = f"ch{chap}/{chap:02d}{sub:02d}{subsub}-{slug.lower()}.sh"
    path = os.path.join(outdir, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    pkg, ver = tarball_for(title)
    if sid in PKG_OVERRIDE:
        pkg = PKG_OVERRIDE[sid]; ver = version_of(pkg)
    with open(path, "w") as f:
        f.write("# Generated by tools/extract-book.py from the LFS book. Do not edit;\n")
        f.write("# put changes in lfs/overrides/ instead.\n")
        f.write(f"# Section: {title}\n# Book id: {sid}\n")
        f.write("# Commands extracted from the LFS book under the MIT License (lfs/book/LICENSE).\n\n")
        for c in cmds:
            c = c.rstrip()
            if TEST.search(c):
                f.write('if [ "${RUN_TESTS:-no}" = yes ]; then\n' + c + "\nfi\n\n")
            else:
                f.write(c + "\n\n")
    index.append(f"{chap}\t{sub}\t{sid}\t{rel}\t{pkg}\t{ver}\t{title}")

with open(os.path.join(outdir, "index.tsv"), "w") as f:
    f.write("chapter\tnumber\tid\tscript\tpackage\tversion\ttitle\n")
    f.write("\n".join(index) + "\n")
print(f"{len(index)} sections written to {outdir}")
